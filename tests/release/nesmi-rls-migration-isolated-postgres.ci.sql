-- Verify RLS and all five owner policies exist in the result of the real migration.
DO $$
DECLARE tbl text; enabled boolean; policies integer;
BEGIN
  FOREACH tbl IN ARRAY ARRAY['team_members','chores','categories','chore_completions','member_availability'] LOOP
    SELECT c.relrowsecurity INTO enabled
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relname=tbl;
    IF enabled IS DISTINCT FROM true THEN RAISE EXCEPTION 'Missing RLS on %', tbl; END IF;
    SELECT count(*) INTO policies FROM pg_policies p
      WHERE p.schemaname='public' AND p.tablename=tbl
        AND p.roles @> ARRAY['authenticated']::name[]
        AND p.cmd='ALL';
    IF policies <> 1 THEN RAISE EXCEPTION 'Expected owner policy on %, found %',tbl,policies; END IF;
  END LOOP;
END $$;

